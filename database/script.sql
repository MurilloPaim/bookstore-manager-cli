SET client_encoding = 'UTF8';

-- =====================================================================
-- SEÇÃO 1 - ESTRUTURA DO BANCO (DDL)
-- =====================================================================

-- Permite executar o script novamente a partir de um banco limpo.
DROP TABLE IF EXISTS emprestimos;
DROP TABLE IF EXISTS livros;
DROP TABLE IF EXISTS clientes;
DROP TABLE IF EXISTS autores;

CREATE TABLE autores (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome          VARCHAR(150) NOT NULL,
    nacionalidade VARCHAR(80)  NOT NULL,
    CONSTRAINT pk_autores PRIMARY KEY (id),
    CONSTRAINT uq_autores_nome UNIQUE (nome)
);

CREATE TABLE livros (
    id                    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    titulo                VARCHAR(200) NOT NULL,
    isbn                  CHAR(13)     NOT NULL,
    ano_publicacao        SMALLINT     NOT NULL,
    autor_id              INTEGER      NOT NULL,
    quantidade_total      INTEGER      NOT NULL,
    quantidade_disponivel INTEGER      NOT NULL,
    CONSTRAINT pk_livros PRIMARY KEY (id),
    CONSTRAINT uq_livros_isbn UNIQUE (isbn),
    CONSTRAINT fk_livros_autor FOREIGN KEY (autor_id)
        REFERENCES autores (id) ON DELETE RESTRICT,
    CONSTRAINT ck_livros_isbn CHECK (isbn ~ '^[0-9]{13}$'),
    CONSTRAINT ck_livros_ano CHECK (ano_publicacao >= 1000),
    CONSTRAINT ck_livros_total CHECK (quantidade_total >= 1),
    CONSTRAINT ck_livros_disponivel CHECK (quantidade_disponivel BETWEEN 0 AND quantidade_total)
);

CREATE TABLE clientes (
    id       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome     VARCHAR(150) NOT NULL,
    cpf      CHAR(11)     NOT NULL,
    email    VARCHAR(150) NOT NULL,
    telefone VARCHAR(11)  NOT NULL,
    CONSTRAINT pk_clientes PRIMARY KEY (id),
    CONSTRAINT uq_clientes_cpf UNIQUE (cpf),
    CONSTRAINT uq_clientes_email UNIQUE (email),
    CONSTRAINT ck_clientes_cpf CHECK (cpf ~ '^[0-9]{11}$'),
    CONSTRAINT ck_clientes_email CHECK (email LIKE '%_@_%._%'),
    CONSTRAINT ck_clientes_telefone CHECK (telefone ~ '^[0-9]{10,11}$')
);

CREATE TABLE emprestimos (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY,
    livro_id        INTEGER     NOT NULL,
    cliente_id      INTEGER     NOT NULL,
    data_emprestimo DATE        NOT NULL DEFAULT CURRENT_DATE,
    data_devolucao  DATE,
    status          VARCHAR(10) NOT NULL DEFAULT 'ATIVO',
    CONSTRAINT pk_emprestimos PRIMARY KEY (id),
    CONSTRAINT fk_emprestimos_livro FOREIGN KEY (livro_id)
        REFERENCES livros (id) ON DELETE RESTRICT,
    CONSTRAINT fk_emprestimos_cliente FOREIGN KEY (cliente_id)
        REFERENCES clientes (id) ON DELETE RESTRICT,
    CONSTRAINT ck_emprestimos_status CHECK (status IN ('ATIVO', 'DEVOLVIDO')),
    CONSTRAINT ck_emprestimos_datas CHECK (data_devolucao IS NULL OR data_devolucao >= data_emprestimo),
    CONSTRAINT ck_emprestimos_status_data CHECK (
        (status = 'ATIVO' AND data_devolucao IS NULL)
        OR (status = 'DEVOLVIDO' AND data_devolucao IS NOT NULL)
    )
);

-- Um cliente não pode estar com dois exemplares do mesmo livro ao mesmo tempo.
CREATE UNIQUE INDEX uq_emprestimo_ativo_livro_cliente
    ON emprestimos (livro_id, cliente_id)
    WHERE status = 'ATIVO';

